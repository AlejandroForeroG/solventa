import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(await fs.readFile(path.join(root, 'brand/source.json'), 'utf8'));
const colors = { green: '#0B6B5F', white: '#FFFFFF', dark: '#062F2A' };
const paths = (part) => part.paths.map(({ d, transform }) =>
  `<path d="${d}"${transform ? ` transform="${transform}"` : ''}/>`).join('\n');
const layouts = {
  logo: { width: source.logo.width + 8, height: source.logo.height + 8, content: `<g transform="translate(4 4)">${paths(source.logo)}</g>`, pngWidth: 240 },
  icon: { width: 424, height: 424, content: `<g transform="translate(${(424 - source.icon.width) / 2} ${(424 - source.icon.height) / 2})">${paths(source.icon)}</g>`, pngWidth: 64 },
  wordmark: { width: source.wordmark.width + 8, height: source.wordmark.height + 8, content: `<g transform="translate(4 4)">${paths(source.wordmark)}</g>`, pngWidth: 240 },
  stacked: { width: 640, height: 500, content: `<g transform="translate(160 24) scale(${320 / source.icon.width})">${paths(source.icon)}</g>\n<g transform="translate(24 362) scale(${592 / source.wordmark.width})">${paths(source.wordmark)}</g>`, pngWidth: 160 },
};
const manifest = {};
let webImports = '', mobileDefinitions = '';
const webEntries = [], mobileEntries = [];
for (const [layout, spec] of Object.entries(layouts)) {
  manifest[layout] = {};
  const webVariants = [], mobileVariants = [];
  for (const [variant, fill] of Object.entries(colors)) {
    const name = `solventa-${layout}-${variant}`;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${spec.width} ${spec.height}" width="${spec.width}" height="${spec.height}" role="img" aria-label="Solventa" fill="${fill}">\n<title>Solventa</title>\n${spec.content}\n</svg>\n`;
    await fs.writeFile(path.join(root, `brand/${name}.svg`), svg);
    const height = Math.round(spec.pngWidth * spec.height / spec.width);
    for (const scale of [1, 2, 3]) {
      const suffix = scale === 1 ? '' : `@${scale}x`;
      await sharp(Buffer.from(svg)).resize(spec.pngWidth * scale, height * scale).png().toFile(path.join(root, `brand/${name}${suffix}.png`));
    }
    manifest[layout][variant] = { svg: `brand/${name}.svg`, png: `brand/${name}.png`, width: spec.width, height: spec.height, aspectRatio: spec.width / spec.height };
    const id = layout + variant[0].toUpperCase() + variant.slice(1);
    webImports += `import ${id} from '../brand/${name}.svg';\n`;
    // Metro requires literal asset paths to include these files in native bundles.
    mobileDefinitions += `const ${id} = require('../brand/${name}.png');\n`;
    webVariants.push(`${variant}: ${id}`);
    mobileVariants.push(`${variant}: ${id}`);
  }
  webEntries.push(`  ${layout}: { ${webVariants.join(', ')} }`);
  mobileEntries.push(`  ${layout}: { ${mobileVariants.join(', ')} }`);
}
const notice = '// Generated by npm run generate --workspace @solventa/assets.\n';
await fs.writeFile(path.join(root, 'src/index.ts'), `${notice}export const brandColors = ${JSON.stringify(colors, null, 2)} as const;\n\n// Package-relative paths for tools and documentation; use /web or /mobile in apps.\nexport const assetPaths = ${JSON.stringify(manifest, null, 2)} as const;\n`);
await fs.writeFile(path.join(root, 'src/web.ts'), `${notice}${webImports}\nexport const brandAssets = {\n${webEntries.join(',\n')}\n} as const;\n`);
await fs.writeFile(path.join(root, 'src/mobile.ts'), `${notice}declare function require(path: string): number;\n\n${mobileDefinitions}\nexport const brandAssets = {\n${mobileEntries.join(',\n')}\n} as const;\n`);
console.log('Generated 12 SVGs, 36 PNGs and shared asset registries.');
